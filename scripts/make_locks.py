"""Regenerate requirements.lock / requirements-dev.lock with sha256 hashes from PyPI.

The pins below are the whole transitive closure; the lock files are installed with
``pip install --require-hashes --no-deps`` so nothing unpinned can sneak in.
"""

from __future__ import annotations

import json
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

RUNTIME: dict[str, str] = {
    "annotated-types": "0.6.0",
    "anyio": "3.7.1",
    "fastapi": "0.115.0",
    "greenlet": "3.0.3",
    "idna": "3.6",
    "pydantic": "2.10.4",
    "pydantic-core": "2.27.2",
    "PyJWT": "2.10.1",
    "PyYAML": "6.0.2",
    "sniffio": "1.3.1",
    "SQLAlchemy": "2.0.36",
    "starlette": "0.38.6",
    "typing-extensions": "4.14.0",
    "certifi": "2024.2.2",
    "h11": "0.14.0",
    "httpcore": "1.0.4",
    "httpx": "0.27.2",
    "iniconfig": "2.0.0",
    "packaging": "23.2",
    "pluggy": "1.6.0",
    "pytest": "8.3.2",
}
MARKERS = {"colorama": 'sys_platform == "win32"'}
RUNTIME["colorama"] = "0.4.6"
DEV: dict[str, str] = {
    "librt": "0.16.0",
    "mypy": "2.4.1",
    "mypy-extensions": "1.1.0",
    "pathspec": "1.1.1",
    "ruff": "0.17.3",
    "types-PyYAML": "6.0.12.20260906",
}


def hashes(name: str, version: str) -> list[str]:
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    with urllib.request.urlopen(url, timeout=30) as resp:
        data = json.load(resp)
    return sorted({f["digests"]["sha256"] for f in data["urls"]})


def render(pins: dict[str, str], header: str) -> str:
    lines = [header]
    for name in sorted(pins, key=str.lower):
        marker = f" ; {MARKERS[name]}" if name in MARKERS else ""
        lines.append(f"{name}=={pins[name]}{marker} \\")
        hs = hashes(name, pins[name])
        lines.extend(
            f"    --hash=sha256:{h}" + (" \\" if i < len(hs) - 1 else "") for i, h in enumerate(hs)
        )
    return "\n".join(lines) + "\n"


def main() -> None:
    head = "# Generated by scripts/make_locks.py -- do not edit by hand.\n"
    (ROOT / "requirements.lock").write_text(render(RUNTIME, head), newline="\n")
    (ROOT / "requirements-dev.lock").write_text(
        render({**RUNTIME, **DEV}, head + "# runtime + lint/type tooling\n"), newline="\n"
    )


if __name__ == "__main__":
    main()
